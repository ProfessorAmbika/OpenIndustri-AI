"""Compile authored missions (tools/authoring/missions/*.py) into shared JSON
content and lazily-loaded locale bundles. Re-run after editing any mission:

    backend/.venv/bin/python tools/build_content.py          # write files
    backend/.venv/bin/python tools/build_content.py --check  # fail if outputs are stale
"""
from __future__ import annotations

import importlib
import json
import pkgutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "backend"))

from authoring import missions as mission_pkg  # noqa: E402
from authoring.dsl import LANGS, Mission  # noqa: E402

SHARED = ROOT / "shared"
LOCALES = ROOT / "frontend" / "src" / "i18n" / "locales" / "missions"
CATEGORY_ORDER = ["og_hazard_recognition", "og_ppe", "og_permit_to_work", "og_loto", "og_confined_space", "og_hot_work",
                  "og_fire_hazard", "og_equipment_inspection", "og_emergency_response"]
HAND_AUTHORED = ["og-hazrec-l1-silent-pump"]


def nest(flat: dict[str, str]) -> dict:
    out: dict = {}
    for key in sorted(flat):
        node = out
        parts = key.split(".")
        for p in parts[:-1]:
            node = node.setdefault(p, {})
            if not isinstance(node, dict):
                raise ValueError(f"key collision at {key}")
        node[parts[-1]] = flat[key]
    return out


def dump(obj: object) -> str:
    return json.dumps(obj, ensure_ascii=False, indent=1) + "\n"


def collect() -> list[Mission]:
    out: list[Mission] = []
    for info in sorted(pkgutil.iter_modules(mission_pkg.__path__), key=lambda i: i.name):
        mod = importlib.import_module(f"authoring.missions.{info.name}")
        out.append(mod.build())
    ids = [m.id for m in out]
    codes = [m.code for m in out]
    if len(set(ids)) != len(ids) or len(set(codes)) != len(codes):
        raise SystemExit("duplicate mission ids or codes")
    slots = [(m.category, m.level) for m in out]
    if len(set(slots)) != len(slots):
        raise SystemExit("two missions occupy the same category/level slot")
    return sorted(out, key=lambda m: (CATEGORY_ORDER.index(m.category), m.level))


def outputs() -> dict[Path, str]:
    from app.content import MissionDef, Question  # validation with the same models the server uses

    missions = collect()
    files: dict[Path, str] = {}
    questions = []
    texts: dict[str, dict[str, str]] = {lang: {} for lang in LANGS}
    for m in missions:
        data = m.build()
        MissionDef.model_validate(data)
        for q in m.questions:
            Question.model_validate(q)
        files[SHARED / "missions" / f"{m.id}.json"] = dump(data)
        questions.extend(m.questions)
        for key, t in m.texts.items():
            for lang in LANGS:
                texts[lang][key] = getattr(t, lang)
    files[SHARED / "content" / "questions.generated.json"] = dump({
        "schemaVersion": 1, "reviewStatus": "draft_unreviewed",
        "note": "GENERATED by tools/build_content.py — do not edit. Draft questions awaiting SME review.",
        "questions": questions,
    })
    for lang in LANGS:
        files[LOCALES / f"{lang}.json"] = dump(nest(texts[lang]))
    cat_path = SHARED / "catalogue.json"
    catalogue = json.loads(cat_path.read_text())
    catalogue["missions"] = HAND_AUTHORED + [m.id for m in missions]
    files[cat_path] = json.dumps(catalogue, ensure_ascii=False, indent=2) + "\n"
    return files


def vectors() -> str:
    """Engine scenarios computed by the Python engine; the TypeScript engine must reproduce them."""
    import copy

    from app import engine
    from app.content import load_catalogue, load_missions
    from app.config import Settings
    from tests.solver import Run, synth

    load_catalogue.cache_clear()
    load_missions.cache_clear()
    from app.content import load_questions, load_references

    load_questions.cache_clear()
    load_references.cache_clear()
    missions = load_missions(Settings().shared_dir)
    out = []

    def record(mid: str, name: str, run: Run) -> None:
        out.append({
            "mission": mid, "name": name, "pathway": run.ctx.pathway,
            "events": [{k: v for k, v in e.items() if v is not None} for e, _ in run.log],
            "results": [{k: r[k] for k in ("outcome", "ruleId", "steps", "missionCompleted") if k in r} for _, r in run.log],
            "final": {"state": run.st.state, "completed": run.st.completed, "flags": run.st.flags, "counters": vars(run.st.counters)},
        })

    for mid, (m, _, _) in missions.items():
        run = Run(m)
        run.solve()
        record(mid, "solution", run)
        for rule in list(m.criticalErrors) + list(m.mistakes):
            run = Run(m)
            for _ in range(80):
                if engine.rule_ok(rule.condition, run.st) and run.st.state in (engine.ACTIVE, engine.BRIEFING):
                    probe = copy.deepcopy(run.st)
                    r = engine.apply(m, probe, {**synth(rule.trigger, m), "seq": run.seq + 1}, run.ctx)
                    if r.get("ruleId") == rule.id:
                        run.emit(synth(rule.trigger, m))
                        if run.st.state == engine.BLOCKED:
                            run.emit({"type": "block_acknowledged", "target": None, "value": None})
                        break
                if run.step_once() is None:
                    break
            run.solve()
            record(mid, f"rule:{rule.id}", run)
    return dump({"note": "GENERATED by tools/build_content.py from backend/app/engine.py — do not edit.", "scenarios": out})


def main() -> None:
    check = "--check" in sys.argv
    files = outputs()
    stale = []
    if not check:
        for path, content in files.items():
            if not path.exists() or path.read_text() != content:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    files[SHARED / "test-vectors" / "generated.json"] = vectors()
    for path, content in files.items():
        if not path.exists() or path.read_text() != content:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    if check and stale:
        raise SystemExit("stale generated content: " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
    print(f"{len(files)} files, {len(stale)} {'stale' if check else 'written'}")


if __name__ == "__main__":
    main()
